//! Reader for (pwiz-written) mzML into [`MsData`].
//!
//! Its job is the writer proof: `write(read(golden)) == golden`. Anything the
//! writer re-derives (cvParam names, encoding cvParams, encoded lengths, counts)
//! is deliberately dropped here so that the writer must reproduce it.

use std::collections::HashMap;

use anyhow::{anyhow, bail, Context, Result};
use quick_xml::events::{BytesStart, Event};
use quick_xml::Reader;

use crate::cv;
use crate::dialect::Dialect;
use crate::encode::{self, Compression, EncoderConfig, Precision};
use crate::model::*;
use crate::xmlwriter::decode_xml_id as dec;

#[derive(Debug, Default)]
struct Node {
    name: String,
    attrs: Vec<(String, String)>,
    children: Vec<Node>,
    text: String,
}

impl Node {
    fn attr(&self, k: &str) -> Option<&str> {
        self.attrs
            .iter()
            .find(|(n, _)| n == k)
            .map(|(_, v)| v.as_str())
    }
    fn attr_s(&self, k: &str) -> String {
        self.attr(k).unwrap_or("").to_string()
    }
    fn id_ref(&self, k: &str) -> Option<String> {
        self.attr(k).map(dec)
    }
    fn child(&self, name: &str) -> Option<&Node> {
        self.children.iter().find(|c| c.name == name)
    }
    fn kids<'a>(&'a self, name: &'a str) -> impl Iterator<Item = &'a Node> + 'a {
        self.children.iter().filter(move |c| c.name == name)
    }
    fn usize_attr(&self, k: &str) -> Result<usize> {
        self.attr(k)
            .ok_or_else(|| anyhow!("<{}> missing {k}", self.name))?
            .parse()
            .with_context(|| format!("<{}> {k}", self.name))
    }
}

fn start_node(e: &BytesStart) -> Result<Node> {
    let mut n = Node {
        name: String::from_utf8(e.name().as_ref().to_vec())?,
        ..Default::default()
    };
    for at in e.attributes() {
        let at = at?;
        let key = String::from_utf8(at.key.as_ref().to_vec())?;
        let val = at.unescape_value()?.into_owned();
        n.attrs.push((key, val));
    }
    Ok(n)
}

fn parse_tree(xml: &[u8]) -> Result<Node> {
    let mut reader = Reader::from_reader(xml);
    reader.config_mut().trim_text(false);
    let mut stack: Vec<Node> = vec![Node {
        name: "#document".into(),
        ..Default::default()
    }];
    let mut buf = Vec::new();
    loop {
        match reader.read_event_into(&mut buf)? {
            Event::Start(e) => stack.push(start_node(&e)?),
            Event::Empty(e) => {
                let n = start_node(&e)?;
                stack.last_mut().unwrap().children.push(n);
            }
            Event::End(_) => {
                let n = stack.pop().unwrap();
                stack
                    .last_mut()
                    .ok_or_else(|| anyhow!("unbalanced XML"))?
                    .children
                    .push(n);
            }
            Event::Text(t) => {
                let top = stack.last_mut().unwrap();
                if top.name == "binary" || top.name == "offset" {
                    top.text.push_str(&t.unescape()?);
                }
            }
            Event::Eof => break,
            _ => {}
        }
        buf.clear();
    }
    let mut doc = stack.pop().ok_or_else(|| anyhow!("empty document"))?;
    // unwrap <indexedmzML> if present
    let root_idx = doc
        .children
        .iter()
        .position(|c| c.name == "mzML" || c.name == "indexedmzML")
        .ok_or_else(|| anyhow!("no <mzML>"))?;
    let mut root = doc.children.swap_remove(root_idx);
    if root.name == "indexedmzML" {
        let i = root
            .children
            .iter()
            .position(|c| c.name == "mzML")
            .ok_or_else(|| anyhow!("no <mzML> in <indexedmzML>"))?;
        root = root.children.swap_remove(i);
    }
    Ok(root)
}

fn params(n: &Node) -> Result<Params> {
    let mut p = Params::default();
    for c in &n.children {
        match c.name.as_str() {
            "referenceableParamGroupRef" => p.group_refs.push(c.attr_s("ref")),
            "cvParam" => {
                p.cv.push(CvParam {
                    accession: c.attr_s("accession"),
                    value: c.attr_s("value"),
                    unit: c.attr("unitAccession").map(str::to_string),
                });
            }
            "userParam" => p.user.push(UserParam {
                name: c.attr_s("name"),
                value: c.attr_s("value"),
                type_: c.attr_s("type"),
                unit: c.attr("unitAccession").map(str::to_string),
            }),
            _ => {}
        }
    }
    Ok(p)
}

/// cvParam / unit names are regenerated by the writer from the CV table of the
/// target pwiz generation; flag any disagreement up front instead of as a diff.
fn check_cv_names(n: &Node, dialect: Dialect) -> Result<()> {
    if n.name == "cvParam" || n.name == "userParam" {
        for (acc_attr, name_attr) in [("accession", "name"), ("unitAccession", "unitName")] {
            if n.name == "userParam" && acc_attr == "accession" {
                continue;
            }
            let Some(acc) = n.attr(acc_attr) else {
                continue;
            };
            let expected = cv::name(dialect, acc)
                .ok_or_else(|| anyhow!("{acc} is not in the {dialect:?} CV table"))?;
            if n.attr(name_attr) != Some(expected) {
                bail!(
                    "{acc}: {name_attr} {:?} differs from the {dialect:?} CV table ({expected:?})",
                    n.attr(name_attr)
                );
            }
        }
    }
    n.children
        .iter()
        .try_for_each(|c| check_cv_names(c, dialect))
}

fn opt_params(n: Option<&Node>) -> Result<Params> {
    n.map(params).transpose().map(|p| p.unwrap_or_default())
}

fn precursor(n: &Node) -> Result<Precursor> {
    Ok(Precursor {
        spectrum_ref: n.attr_s("spectrumRef"),
        source_file_ref: n.id_ref("sourceFileRef"),
        external_spectrum_id: n.attr_s("externalSpectrumID"),
        params: params(n)?,
        isolation_window: opt_params(n.child("isolationWindow"))?,
        selected_ions: n
            .child("selectedIonList")
            .map(|l| l.kids("selectedIon").map(params).collect())
            .transpose()?
            .unwrap_or_default(),
        activation: opt_params(n.child("activation"))?,
    })
}

fn product(n: &Node) -> Result<Product> {
    Ok(Product {
        isolation_window: opt_params(n.child("isolationWindow"))?,
    })
}

/// Encoding observed in the file, accumulated into an [`EncoderConfig`].
#[derive(Default)]
struct EncodingSeen {
    compression: Option<Compression>,
    by_kind: HashMap<String, Precision>,
    unkeyed: Option<Precision>,
}

impl EncodingSeen {
    fn note(&mut self, kind: Option<&str>, p: Precision, c: Compression) -> Result<()> {
        match self.compression {
            None => self.compression = Some(c),
            Some(prev) if prev != c => {
                bail!("mixed compression in one file is not representable by one pwiz config")
            }
            _ => {}
        }
        let slot = match kind {
            Some(k) => self.by_kind.entry(k.to_string()).or_insert(p),
            None => self.unkeyed.get_or_insert(p),
        };
        if *slot != p {
            bail!("array kind {kind:?} written with mixed precision");
        }
        Ok(())
    }

    fn config(self, dialect: Dialect) -> EncoderConfig {
        EncoderConfig {
            dialect,
            precision: self.unkeyed.unwrap_or(Precision::P64),
            compression: self.compression.unwrap_or(Compression::None),
            precision_overrides: self.by_kind,
        }
    }
}

fn binary_array(n: &Node, seen: &mut EncodingSeen) -> Result<BinaryDataArray> {
    let all = params(n)?;
    let (mut precision, mut integer, mut compression) = (None, false, None);
    let mut kept = Params {
        group_refs: all.group_refs,
        user: all.user,
        cv: Vec::new(),
    };
    for p in all.cv {
        match p.accession.as_str() {
            cv::encoding::FLOAT_32 => precision = Some(Precision::P32),
            cv::encoding::FLOAT_64 => precision = Some(Precision::P64),
            cv::encoding::INT_32 => (precision, integer) = (Some(Precision::P32), true),
            cv::encoding::INT_64 => (precision, integer) = (Some(Precision::P64), true),
            cv::encoding::NO_COMPRESSION => compression = Some(Compression::None),
            cv::encoding::ZLIB => compression = Some(Compression::Zlib),
            "MS:1002312" | "MS:1002313" | "MS:1002314" | "MS:1002746" | "MS:1002747"
            | "MS:1002748" => {
                bail!("numpress encoding is not supported ({})", p.accession)
            }
            _ => kept.cv.push(p),
        }
    }
    let precision = precision.ok_or_else(|| anyhow!("binaryDataArray without precision term"))?;
    let compression =
        compression.ok_or_else(|| anyhow!("binaryDataArray without compression term"))?;
    let text = n.child("binary").map(|b| b.text.as_str()).unwrap_or("");
    let data = encode::decode(text, precision, compression, integer)?;
    let arr = BinaryDataArray {
        params: kept,
        data_processing_ref: n.id_ref("dataProcessingRef"),
        data,
    };
    seen.note(arr.kind(), precision, compression)?;
    Ok(arr)
}

fn arrays(n: &Node, seen: &mut EncodingSeen) -> Result<Vec<BinaryDataArray>> {
    match n.child("binaryDataArrayList") {
        Some(l) => l
            .kids("binaryDataArray")
            .map(|b| binary_array(b, seen))
            .collect(),
        None => Ok(Vec::new()),
    }
}

fn spectrum(n: &Node, seen: &mut EncodingSeen) -> Result<Spectrum> {
    let sl = n.child("scanList");
    let scan_list = match sl {
        Some(sl) => ScanList {
            params: params(sl)?,
            scans: sl
                .kids("scan")
                .map(|s| {
                    Ok(Scan {
                        spectrum_ref: s.attr_s("spectrumRef"),
                        source_file_ref: s.id_ref("sourceFileRef"),
                        external_spectrum_id: s.attr_s("externalSpectrumID"),
                        instrument_configuration_ref: s.id_ref("instrumentConfigurationRef"),
                        params: params(s)?,
                        scan_windows: s
                            .child("scanWindowList")
                            .map(|l| l.kids("scanWindow").map(params).collect())
                            .transpose()?
                            .unwrap_or_default(),
                    })
                })
                .collect::<Result<_>>()?,
        },
        None => ScanList::default(),
    };
    Ok(Spectrum {
        index: n.usize_attr("index")?,
        id: n.attr_s("id"),
        spot_id: n.attr_s("spotID"),
        default_array_length: n.usize_attr("defaultArrayLength")?,
        data_processing_ref: n.id_ref("dataProcessingRef"),
        source_file_ref: n.id_ref("sourceFileRef"),
        params: params(n)?,
        scan_list,
        precursors: n
            .child("precursorList")
            .map(|l| l.kids("precursor").map(precursor).collect())
            .transpose()?
            .unwrap_or_default(),
        products: n
            .child("productList")
            .map(|l| l.kids("product").map(product).collect())
            .transpose()?
            .unwrap_or_default(),
        arrays: arrays(n, seen)?,
    })
}

fn chromatogram(n: &Node, seen: &mut EncodingSeen) -> Result<Chromatogram> {
    Ok(Chromatogram {
        index: n.usize_attr("index")?,
        id: n.attr_s("id"),
        default_array_length: n.usize_attr("defaultArrayLength")?,
        data_processing_ref: n.id_ref("dataProcessingRef"),
        params: params(n)?,
        precursor: n
            .child("precursor")
            .map(precursor)
            .transpose()?
            .unwrap_or_default(),
        product: n
            .child("product")
            .map(product)
            .transpose()?
            .unwrap_or_default(),
        arrays: arrays(n, seen)?,
    })
}

/// Parse mzML (plain or indexed) into the model plus the encoder config (and
/// serializer dialect) the file was evidently written with.
pub fn read_mzml(xml: &[u8]) -> Result<(MsData, EncoderConfig)> {
    let dialect = Dialect::sniff(xml);
    let root = parse_tree(xml)?;
    check_cv_names(&root, dialect)?;
    // C++ writes the list-level defaultDataProcessingRef raw, C# id-encodes it.
    let list_dp_ref = |n: &Node| match dialect {
        Dialect::Pwiz3Cpp => n.attr("defaultDataProcessingRef").map(str::to_string),
        Dialect::Pwiz4Net => n.id_ref("defaultDataProcessingRef"),
    };
    let mut seen = EncodingSeen::default();
    let mut msd = MsData {
        accession: root.attr_s("accession"),
        id: root.attr_s("id"),
        version: root.attr_s("version"),
        ..Default::default()
    };

    if let Some(l) = root.child("cvList") {
        for c in l.kids("cv") {
            msd.cvs.push(Cv {
                id: dec(&c.attr_s("id")),
                full_name: c.attr_s("fullName"),
                version: c.attr_s("version"),
                uri: c.attr_s("URI"),
            });
        }
    }
    if let Some(fd) = root.child("fileDescription") {
        msd.file_description.file_content = opt_params(fd.child("fileContent"))?;
        if let Some(l) = fd.child("sourceFileList") {
            for sf in l.kids("sourceFile") {
                msd.file_description.source_files.push(SourceFile {
                    id: dec(&sf.attr_s("id")),
                    name: sf.attr_s("name"),
                    location: sf.attr_s("location"),
                    params: params(sf)?,
                });
            }
        }
        for c in fd.kids("contact") {
            msd.file_description.contacts.push(params(c)?);
        }
    }
    if let Some(l) = root.child("referenceableParamGroupList") {
        for g in l.kids("referenceableParamGroup") {
            msd.param_groups.push(ParamGroup {
                id: dec(&g.attr_s("id")),
                params: params(g)?,
            });
        }
    }
    if let Some(l) = root.child("sampleList") {
        for s in l.kids("sample") {
            msd.samples.push(Sample {
                id: dec(&s.attr_s("id")),
                name: s.attr_s("name"),
                params: params(s)?,
            });
        }
    }
    if let Some(l) = root.child("softwareList") {
        for s in l.kids("software") {
            msd.software.push(Software {
                id: dec(&s.attr_s("id")),
                version: s.attr_s("version"),
                params: params(s)?,
            });
        }
    }
    if let Some(l) = root.child("scanSettingsList") {
        for s in l.kids("scanSettings") {
            msd.scan_settings.push(ScanSettings {
                id: dec(&s.attr_s("id")),
                source_file_refs: s
                    .child("sourceFileRefList")
                    .map(|l| {
                        l.kids("sourceFileRef")
                            .map(|r| dec(&r.attr_s("ref")))
                            .collect()
                    })
                    .unwrap_or_default(),
                targets: s
                    .child("targetList")
                    .map(|l| l.kids("target").map(params).collect())
                    .transpose()?
                    .unwrap_or_default(),
            });
        }
    }
    if let Some(l) = root.child("instrumentConfigurationList") {
        for ic in l.kids("instrumentConfiguration") {
            let mut components = Vec::new();
            if let Some(cl) = ic.child("componentList") {
                for c in &cl.children {
                    let kind = match c.name.as_str() {
                        "source" => ComponentKind::Source,
                        "analyzer" => ComponentKind::Analyzer,
                        "detector" => ComponentKind::Detector,
                        _ => continue,
                    };
                    components.push(Component {
                        kind,
                        order: c.attr_s("order").parse()?,
                        params: params(c)?,
                    });
                }
            }
            msd.instrument_configurations.push(InstrumentConfiguration {
                id: dec(&ic.attr_s("id")),
                params: params(ic)?,
                components,
                software_ref: ic.child("softwareRef").map(|r| dec(&r.attr_s("ref"))),
            });
        }
    }
    if let Some(l) = root.child("dataProcessingList") {
        for dp in l.kids("dataProcessing") {
            let mut methods = Vec::new();
            for m in dp.kids("processingMethod") {
                methods.push(ProcessingMethod {
                    order: m.attr_s("order").parse()?,
                    software_ref: m.id_ref("softwareRef"),
                    params: params(m)?,
                });
            }
            msd.data_processing.push(DataProcessing {
                id: dec(&dp.attr_s("id")),
                methods,
            });
        }
    }
    let run = root.child("run").ok_or_else(|| anyhow!("no <run>"))?;
    msd.run = Run {
        id: dec(&run.attr_s("id")),
        default_instrument_configuration_ref: run.id_ref("defaultInstrumentConfigurationRef"),
        sample_ref: run.id_ref("sampleRef"),
        start_time_stamp: run.attr_s("startTimeStamp"),
        default_source_file_ref: run.id_ref("defaultSourceFileRef"),
        params: params(run)?,
        ..Default::default()
    };
    if let Some(sl) = run.child("spectrumList") {
        msd.run.spectrum_default_data_processing_ref = list_dp_ref(sl);
        for s in sl.kids("spectrum") {
            msd.run.spectra.push(spectrum(s, &mut seen)?);
        }
    }
    if let Some(cl) = run.child("chromatogramList") {
        msd.run.chromatogram_default_data_processing_ref = list_dp_ref(cl);
        for c in cl.kids("chromatogram") {
            msd.run.chromatograms.push(chromatogram(c, &mut seen)?);
        }
    }
    Ok((msd, seen.config(dialect)))
}
